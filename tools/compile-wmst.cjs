'use strict';

// Compiles contracts/wMST.sol with solc-js and writes the committed artifacts:
//   contracts/wMST.artifact.json  - ABI, bytecode, selectors, compiler settings
//   wmst-artifact.js              - the same data for setup.html (browser global)
// Usage: npm install --no-save solc@0.8.28 && node tools/compile-wmst.cjs
// SOLC_MODULE may point at a solc package directory installed elsewhere.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '..');
const solc = require(process.env.SOLC_MODULE || 'solc');
const source = fs.readFileSync(path.join(root, 'contracts/wMST.sol'), 'utf8');
const input = {
  language: 'Solidity',
  sources: { 'wMST.sol': { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 10000 },
    // Chain 7601 rejects PUSH0 (Shanghai), so stay on Paris opcodes.
    evmVersion: 'paris',
    metadata: { bytecodeHash: 'none' },
    outputSelection: { 'wMST.sol': { WMST: ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'evm.methodIdentifiers', 'evm.gasEstimates'] } }
  }
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors || []).filter(item => item.severity === 'error');
for (const item of output.errors || []) console.error(item.formattedMessage);
if (errors.length) process.exit(1);
const contract = output.contracts['wMST.sol'].WMST;
const artifact = {
  contractName: 'WMST',
  compiler: { name: 'solc', version: solc.version(), optimizer: input.settings.optimizer, evmVersion: input.settings.evmVersion },
  sourceSha256: crypto.createHash('sha256').update(source).digest('hex'),
  abi: contract.abi,
  bytecode: '0x' + contract.evm.bytecode.object,
  deployedBytecode: '0x' + contract.evm.deployedBytecode.object,
  methodIdentifiers: contract.evm.methodIdentifiers,
  gasEstimates: contract.evm.gasEstimates
};
fs.writeFileSync(path.join(root, 'contracts/wMST.artifact.json'), JSON.stringify(artifact, null, 2) + '\n');
const browser = { contractName: artifact.contractName, compiler: artifact.compiler, sourceSha256: artifact.sourceSha256, abi: artifact.abi, bytecode: artifact.bytecode, methodIdentifiers: artifact.methodIdentifiers };
fs.writeFileSync(path.join(root, 'wmst-artifact.js'), '// Generated by tools/compile-wmst.cjs from contracts/wMST.sol. Do not edit.\nwindow.WMST_ARTIFACT = ' + JSON.stringify(browser) + ';\n');
console.log(JSON.stringify({ version: artifact.compiler.version, bytecodeBytes: (artifact.bytecode.length - 2) / 2, deployedBytes: (artifact.deployedBytecode.length - 2) / 2, methodIdentifiers: artifact.methodIdentifiers }, null, 2));
